import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createToastStore, TOAST_DEFAULTS } from './toastStore'
import { publicOperationMessage, requiresContext } from './operationFeedback'

let store
beforeEach(() => { vi.useFakeTimers(); store = createToastStore({ exitMs: 0 }) })
afterEach(() => { store.dispose(); expect(vi.getTimerCount()).toBe(0); vi.useRealTimers() })
describe('cola corporativa', () => {
  it('termina la animación de salida antes de promover el siguiente aviso y limpia su timer', () => {
    store = createToastStore({ limit: 1 })
    const id = store.api.success('Primero')
    store.api.error('Segundo')
    store.api.dismiss(id)
    expect(store.getSnapshot()[0].closing).toBe(true)
    vi.advanceTimersByTime(140)
    expect(store.getSnapshot()[0].message).toBe('Segundo')
    expect(vi.getTimerCount()).toBe(1)
  })
  it.each(Object.entries(TOAST_DEFAULTS))('%s respeta su duración %i', (type, duration) => {
    store.api[type]('Resultado confirmado')
    vi.advanceTimersByTime(duration - 1)
    expect(store.getSnapshot()).toHaveLength(1)
    vi.advanceTimersByTime(1)
    expect(store.getSnapshot()).toHaveLength(0)
  })
  it('asigna IDs, muestra tres y promueve FIFO sin gastar el tiempo de la cola', () => {
    const ids = [1, 2, 3, 4, 5].map(i => store.api.error(`Operación ${i}`))
    expect(new Set(ids).size).toBe(5)
    expect(store.getSnapshot().map(t => t.message)).toEqual(['Operación 1', 'Operación 2', 'Operación 3'])
    vi.advanceTimersByTime(4000)
    store.api.dismiss(ids[1])
    expect(store.getSnapshot().map(t => t.message)).toEqual(['Operación 1', 'Operación 3', 'Operación 4'])
    vi.advanceTimersByTime(4000)
    expect(store.getSnapshot().map(t => t.message)).toEqual(['Operación 4', 'Operación 5'])
    vi.advanceTimersByTime(3999)
    expect(store.getSnapshot()).toHaveLength(2)
    vi.advanceTimersByTime(1)
    expect(store.getSnapshot().map(t => t.message)).toEqual(['Operación 5'])
  })
  it('pausa por motivos independientes y reanuda solamente el tiempo restante', () => {
    const id = store.api.success('Guardado')
    vi.advanceTimersByTime(2000)
    store.pause(id, 'pointer', true)
    store.pause(id, 'focus', true)
    vi.advanceTimersByTime(20000)
    store.pause(id, 'pointer', false)
    vi.advanceTimersByTime(10000)
    expect(store.getSnapshot()).toHaveLength(1)
    store.pause(id, 'focus', false)
    vi.advanceTimersByTime(2999)
    expect(store.getSnapshot()).toHaveLength(1)
    vi.advanceTimersByTime(1)
    expect(store.getSnapshot()).toHaveLength(0)
  })
  it('deduplica origen y operación, sin confundir operaciones con textos iguales', () => {
    const first = store.api.error('Falló', { source: 'orders', operation: 'one' })
    expect(store.api.error('Falló', { source: 'orders', operation: 'one' })).toBe(first)
    expect(store.api.error('Falló', { source: 'orders', operation: 'two' })).not.toBe(first)
    expect(store.api.error('Falló', { source: 'users', operation: 'one' })).not.toBe(first)
    store.api.error('Falló')
    store.api.dismiss(first)
    expect(store.getSnapshot()).toHaveLength(3)
  })
  it('adapta el límite sin perder eventos y pausa los retirados de la pantalla', () => {
    const first = store.api.success('Uno')
    store.api.success('Dos')
    vi.advanceTimersByTime(2000)
    store.setLimit(1)
    vi.advanceTimersByTime(3000)
    expect(store.getSnapshot()[0].message).toBe('Dos')
    store.api.dismiss(first)
    vi.advanceTimersByTime(2999)
    expect(store.getSnapshot()).toHaveLength(1)
  })
  it('cierra sesión, limpia timers y rechaza promesas tardías del productor anterior', () => {
    const stale = store.api
    stale.error('Anterior')
    stale.endSession()
    expect(stale.success('Respuesta tardía')).toBeNull()
    expect(store.getSnapshot()).toHaveLength(0)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('un hover o foco que desaparece al reducir la pila no congela la cola', () => {
    const first = store.api.info('Primero'), second = store.api.info('Segundo')
    store.pause(second, 'focus', true)
    store.pause(second, 'pointer', true)
    store.setLimit(1)
    store.api.dismiss(first)
    vi.advanceTimersByTime(5000)
    expect(store.getSnapshot()).toHaveLength(0)
  })
  it('desmonta sin timers y permite limpiar sin inutilizar una sesión vigente', () => {
    store.api.info('Primero')
    store.api.clear()
    expect(store.api.info('Segundo')).toBeTruthy()
    store.dispose()
    expect(store.api.info('Desmontado')).toBeNull()
  })
  it('usa texto público seguro y clasifica PIN y conciliación como contextuales', () => {
    expect(publicOperationMessage({ payload: { message: '<script>secret</script>' } }, 'No se pudo guardar')).toBe('No se pudo guardar')
    expect(publicOperationMessage({ payload: { message: 'PrismaClient: SELECT password' } }, 'No se pudo guardar')).toBe('No se pudo guardar')
    expect(publicOperationMessage({ payload: { message: 'Debes confirmar el pago.' } }, 'Error')).toBe('Debes confirmar el pago.')
    expect(requiresContext({ payload: { code: 'PIN_INVALID' } })).toBe(true)
    expect(requiresContext({ payload: { code: 'USER_UPDATE_PENDING_RECONCILIATION' } })).toBe(true)
  })
})
